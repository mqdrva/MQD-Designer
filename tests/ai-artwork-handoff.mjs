import assert from 'node:assert/strict';
import {sanitizePlan,encodePlan,decodePlan,AI_PRODUCTS,AI_TSHIRT_CHEST_LAYOUT} from '../v20/ai-design-contract.js';
import {buildDraftPayload} from '../v20/ai-draft-builder.js';
const contextId='a'.repeat(32);
const plan=sanitizePlan({contextId,productId:'tshirt',zones:AI_PRODUCTS[0].zones.map(zone=>({zone,background:'#000000',elements:[{kind:'artwork',scale:1},...(zone==='Front'?[{kind:'logo',scale:.4,y:-15}]:zone==='Back'?[{kind:'logo',scale:.22,y:-15},{kind:'text',text:'888-888-8888',color:'#FFFFFF',y:25}]:[])]}))});
const decoded=decodePlan(encodePlan(plan));
assert.equal(decoded.contextId,contextId);
assert.deepEqual(decoded.zones,plan.zones);
const chatReturnToken=Buffer.from(JSON.stringify(plan),'utf8').toString('base64url');
assert.deepEqual(decodePlan(chatReturnToken).zones,plan.zones,'ChatGPT-computed return links preserve the complete layout');
assert.equal(decodePlan(chatReturnToken).contextId,contextId,'Return links restore only their own saved images');
assert.equal(decodePlan(encodePlan(plan).slice(0,-1)+'!'),null);
const legacy='WzIsMCxbWzAsIjAwMDAwMCIsW1sxLCJURVNUIERFU0lHTiIsMCwwLDEsMCwiRkYwMDAwIiwiMDAwMDAwIiwwLDAsMSwwLDFdXV1dXQ.fehcj1';
assert.equal(decodePlan(legacy).zones[0].elements[0].text,'TEST DESIGN');
const logo={src:'data:image/png;base64,logo',filename:'logo.png',width:3000,height:1000};
const artwork={src:'data:image/png;base64,artwork',filename:'water.png'};
assert.throws(()=>buildDraftPayload(plan,{logo},{}),/background image/);
assert.throws(()=>buildDraftPayload(plan,{artwork},{}),/your logo/);
const current={product:{id:'tshirt'},templates:Object.fromEntries(AI_PRODUCTS[0].zones.map(zone=>[zone,{width:3000,height:4000}])),design:{zones:{Front:{layers:[{id:'customer',type:'text',text:'Keep me'}]}}}};
const before=JSON.stringify(current);
const payload=buildDraftPayload(plan,{logo,artwork},current);
assert.equal(JSON.stringify(current),before);
assert.deepEqual(Object.keys(payload.product),['id']);
assert.equal(payload.design.zones.Front.layers[0].src,artwork.src);
assert.equal(payload.design.zones.Front.layers[1].src,logo.src);
assert.equal(payload.design.zones.Front.layers[2].text,'Keep me');
assert.equal(payload.design.zones.Back.layers[1].scale,.22/4);
assert.equal(payload.design.zones.Front.layers[1].scale,.4/4,'Wide logo is contained, not cropped by cover-fit');
assert.equal(payload.design.zones.Back.layers[2].text,'888-888-8888');
for(const zone of AI_PRODUCTS[0].zones)assert.equal(payload.design.zones[zone].layers[0].src,artwork.src);
const revised=buildDraftPayload(plan,{logo,artwork},{...payload,templates:current.templates});
assert.equal(revised.design.zones.Front.layers.length,3,'Reapplying duplicates neither customer nor AI layers');
const crowded={product:{id:'tshirt'},design:{zones:{Front:{layers:Array.from({length:6},(_,id)=>({id,type:'text'}))}}}};
assert.throws(()=>buildDraftPayload(plan,{logo,artwork},crowded),/six layers/);
const chestPlan=sanitizePlan({productId:'tshirt',zones:[
  {zone:'Front',elements:[AI_TSHIRT_CHEST_LAYOUT.frontLogo]},
  {zone:'Back',elements:[AI_TSHIRT_CHEST_LAYOUT.backLogo,{...AI_TSHIRT_CHEST_LAYOUT.backPhone,text:'888-888-8888'}]}
]});
assert.deepEqual(decodePlan(encodePlan(chestPlan)).zones,chestPlan.zones,'Chest layout and phone spacing survive a draft-link round trip');
const chest=buildDraftPayload(chestPlan,{logo},current);
assert.equal(chest.design.zones.Front.layers[0].aiZone,'Front');
assert.equal(chest.design.zones.Front.layers[0].y,-30,'2D front position is independent of 3D calibration');
assert.equal(chest.design.zones.Back.layers[0].aiZone,'Back');
assert.equal(chest.design.zones.Back.layers[0].y,-55);
assert.equal(chest.design.zones.Back.layers[1].y,-25);
assert.equal(chest.design.zones.Back.layers[1].scale,.89);
assert.equal(chest.design.zones.Back.layers[1].letterSpacing,5);
console.log('Artwork draft regression passed: complete images required, logo preserved, background below foreground, phone/back scale correct, no layer loss or duplicated revisions.');
