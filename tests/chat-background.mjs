import assert from 'node:assert/strict';
import {addChatBackground,backgroundPrompt} from '../v20/chat-background-payload.js';
const logo={id:'logo',type:'image',src:'logo',x:12,y:-30,scale:.54,aiManaged:true,aiAssetKind:'logo'};
const text={id:'phone',type:'text',text:'888-888-8888',y:-25,scale:.89};
const current={product:{id:'tshirt'},activeZone:'Front',templates:{Front:{},Back:{}},design:{zones:{Front:{background:'#000000',layers:[logo]},Back:{background:'#000000',layers:[text]}}}};
const before=JSON.stringify(current),asset={src:'data:image/png;base64,background',filename:'existing.png'};
const applied=addChatBackground(current,asset,['Front','Back']);
assert.equal(JSON.stringify(current),before);
assert.deepEqual(applied.design.zones.Front.layers[1],logo);
assert.deepEqual(applied.design.zones.Back.layers[1],text);
assert.equal(applied.design.zones.Front.layers[0].src,asset.src);
assert.equal(applied.design.zones.Back.layers[0].src,asset.src);
const replaced=addChatBackground(applied,{...asset,src:'replacement'},['Front']);
assert.equal(replaced.design.zones.Front.layers.length,2);
assert.equal(replaced.design.zones.Back.layers[0].src,asset.src);
assert.deepEqual(replaced.design.zones.Front.layers[1],logo);
const full=structuredClone(current);full.design.zones.Back.layers=Array.from({length:6},(_,id)=>({...text,id}));
assert.throws(()=>addChatBackground(full,asset,['Front','Back']),/six layers/);
assert.equal(full.design.zones.Front.layers.length,1);
assert.throws(()=>addChatBackground(current,asset,['Unknown']),/current garment/);
assert.match(backgroundPrompt('blue water'),/blue water/);
console.log('Background upload checks passed: original layers and positions preserved, background below artwork, replacement without duplicates, selected-area isolation, atomic layer-limit rejection. No AI calls.');
