import assert from 'node:assert/strict';
import { installPhotoPreviewZoom } from '../v20/photo-preview-zoom.js';
globalThis.ResizeObserver=class { observe(){} };
const listeners={}; let image=true;
const canvas={style:{},clientWidth:300,clientHeight:400,width:800,height:900,parentElement:{getBoundingClientRect:()=>({left:0,top:0})},addEventListener:(n,f)=>listeners[n]=f,setPointerCapture(){}};
const zoom=installPhotoPreviewZoom(canvas,()=>image);
const send=(type,id,x,y,extra={})=>listeners[type]?.({type,pointerId:id,clientX:x,clientY:y,pointerType:'touch',preventDefault(){},...extra});
send('pointerdown',1,100,100); send('pointerdown',2,200,100);
send('pointermove',2,300,100);
assert.equal(canvas.style.transform,'translate(-100px, -100px) scale(2)');
send('pointermove',2,1000,100); assert.match(canvas.style.transform,/scale\(4\)$/);
send('pointercancel',2,1000,100); send('pointercancel',1,100,100);
zoom.reset(); assert.equal(canvas.style.transform,'translate(0px, 0px) scale(1)');
listeners.wheel({ctrlKey:true,clientX:150,clientY:200,deltaY:-100,preventDefault(){}});
assert.notEqual(canvas.style.transform,'translate(0px, 0px) scale(1)');
assert.equal(canvas.width,800); assert.equal(canvas.height,900);
zoom.reset(); image=false; zoom.reset(); send('pointerdown',1,10,10); send('pointerdown',2,20,10); send('pointermove',2,200,10);
assert.equal(canvas.style.transform,'translate(0px, 0px) scale(1)');
assert.equal(canvas.style.touchAction,'auto');
console.log('Pinch zoom, bounds, cancellation, reset, trackpad and unchanged export pixels passed.');
