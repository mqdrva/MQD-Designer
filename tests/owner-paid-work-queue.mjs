import assert from 'node:assert/strict';
import fs from 'node:fs';
import {classifyOwnerOrder,ownerWorkQueue} from '../supabase/functions/_shared/mqd-owner-work-queue.js';
const unpaid={id:'unpaid',status:'submitted',is_test:false,stripe_payment_status:null,paid_at:null,amount_paid:null};
const paid={id:'paid',status:'paid',is_test:false,stripe_payment_status:'paid',paid_at:'2026-10-14T00:00:00Z',amount_paid:144};
const shipped={...paid,id:'shipped',status:'shipped'};
const test={...paid,id:'test',is_test:true};
const cancelled={...paid,id:'cancelled',status:'cancelled'};
const refunded={...paid,id:'refunded',stripe_payment_status:'refunded'};
const rows=[unpaid,paid,shipped,test,cancelled,refunded];
const primary=ownerWorkQueue(rows);
assert.deepEqual(primary.filtered.map(r=>r.id),['paid','shipped','cancelled','refunded']);
assert.equal(primary.counts.all,4);assert.equal(primary.counts.unpaid,1);assert.equal(primary.counts.new,1);assert.equal(primary.counts.test,1);assert.equal(primary.counts.paid,1);assert.equal(primary.counts.shipped,1);
assert.deepEqual(ownerWorkQueue(rows,'unpaid').filtered.map(r=>r.id),['unpaid']);
assert.deepEqual(ownerWorkQueue(rows,'new').filtered.map(r=>r.id),['unpaid']);
assert.deepEqual(ownerWorkQueue(rows,'test').filtered.map(r=>r.id),['test']);
assert.deepEqual(ownerWorkQueue(rows,'review').filtered.map(r=>r.id),['cancelled','refunded']);
for(const status of ['production','shipped','completed'])assert.equal(classifyOwnerOrder({...paid,status}).payment_confirmed,true);
assert.equal(classifyOwnerOrder({...unpaid,status:'paid'}).payment_confirmed,false,'A manually named status is not payment proof');
assert.equal(classifyOwnerOrder({...paid,stripe_payment_status:null}).payment_confirmed,true,'Preserve legacy dated positive receipts');
assert.equal(classifyOwnerOrder(refunded).ui_status,'payment-review');
assert.equal(classifyOwnerOrder({...paid,stripe_payment_status:'failed'}).ui_status,'payment-review');
assert.equal(classifyOwnerOrder({...unpaid,stripe_payment_status:'paid',amount_paid:0}).payment_confirmed,true,'Authoritative zero-total paid sessions remain paid');
assert.equal(ownerWorkQueue([...rows,{...unpaid,id:'another-attempt'}]).counts.all,4);
const source=fs.readFileSync(new URL('../supabase/functions/mqd-owner-orders/index.ts',import.meta.url),'utf8');
assert.match(source,/payment\.payment_review_reason\|\|/);
assert.match(source,/!payment\.payment_confirmed/);
assert.match(source,/Only confirmed paid orders/);
const html=fs.readFileSync(new URL('../owner-orders.html',import.meta.url),'utf8');assert.match(html,/Unpaid Submissions/);assert.match(html,/Payment review/);assert.match(html,/Ready to Produce/);
const ui=fs.readFileSync(new URL('../v20/owner-orders.js',import.meta.url),'utf8');
assert.ok(ui.includes("$('testOrderNotice').classList.toggle('hidden',order.is_test!==true)"),'Only actual test orders show the sandbox notice');
console.log('PASS paid owner queue: unpaid attempts excluded from production counts, paid fulfillment retained, refunds/cancellations held for review, legacy receipts supported, test orders separate.');
