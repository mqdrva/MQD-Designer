alter table public.mqd_library_asset_placements enable row level security;
alter table public.mqd_library_asset_placements force row level security;

revoke all on public.mqd_library_assets from anon, authenticated;
revoke all on public.mqd_library_asset_placements from anon, authenticated;

create index if not exists mqd_library_assets_active_sort_idx on public.mqd_library_assets(active,sort_order,name);
create index if not exists mqd_library_placements_context_idx on public.mqd_library_asset_placements(product_id,zone_name,asset_id);

